<script setup lang="ts">
const props = defineProps<{
  districtName: string
  year: string
  sourceUrl: string
  district: any
  cal: any
}>()

const pdfUrl = computed(() => String(props.cal?.sourcePdfUrl ?? props.cal?.printablePdfUrl ?? ''))
const hasOfficialPdf = computed(() => Boolean(props.cal?.sourcePdfUrl))
const hasGeneratedPrintablePdf = computed(() => !hasOfficialPdf.value && Boolean(props.cal?.printablePdfUrl))
const isDrivePdf = computed(() => pdfUrl.value.includes('drive.google.com'))
const isArchivedPdfCopy = computed(() => pdfUrl.value.includes('assets.myschooldates.com'))
const compactDownloadModule = computed(() => Boolean(props.cal?.compactDownloadModule ?? props.cal?.meta?.compactDownloadModule))
const hideCompatibleCalendars = computed(() => Boolean(props.cal?.hideCompatibleCalendars ?? props.cal?.meta?.hideCompatibleCalendars))
const hidePdfVersionLabel = computed(() => Boolean(props.cal?.hidePdfVersionLabel ?? props.cal?.meta?.hidePdfVersionLabel))
const hideExtendedShareButtons = computed(() => Boolean(props.cal?.hideExtendedShareButtons ?? props.cal?.meta?.hideExtendedShareButtons))
const hideShareCalendar = computed(() => Boolean(props.cal?.hideShareCalendar ?? props.cal?.meta?.hideShareCalendar))
const hideIcsButtonSupportText = computed(() => Boolean(props.cal?.hideIcsButtonSupportText ?? props.cal?.meta?.hideIcsButtonSupportText))
const displayYear = computed(() => props.cal?.displaySchoolYear ?? props.cal?.meta?.displaySchoolYear ?? props.year)
const pdfHeading = computed(() => {
  const customHeading = props.cal?.pdfHeading ?? props.cal?.meta?.pdfHeading
  if (customHeading) return customHeading
  if (isArchivedPdfCopy.value) return `${props.districtName} Calendar ${displayYear.value}: Official Calendar PDF — Archived Copy`
  if (hasGeneratedPrintablePdf.value) return `${props.districtName} Calendar ${displayYear.value}: Printable PDF`
  if (isDrivePdf.value) return `${props.districtName} Calendar ${displayYear.value}: Printable PDF`
  return `${props.districtName} Calendar ${displayYear.value}: Printable PDF`
})
const pdfDescription = computed(() => {
  const customDescription = props.cal?.pdfDescription ?? props.cal?.meta?.pdfDescription
  if (customDescription) return customDescription
  if (isArchivedPdfCopy.value) {
    return `This is an archived copy of the official ${props.year} calendar published by ${props.districtName}. MySchoolDates stores the file for reliable long-term access because original district file URLs may expire. Check the official district source for revisions or newer versions.`
  }
  if (hasGeneratedPrintablePdf.value) {
    return `Download a printable PDF generated by MySchoolDates from the reviewed ${props.year} ${props.districtName} calendar records. The official district calendar remains the source of record for revisions and last-minute changes.`
  }
  if (isDrivePdf.value) {
    return `Open or print the calendar PDF linked from the ${props.districtName} calendar page. Check the district calendar page for revisions before making travel or child care plans.`
  }
  return `Open or print the official calendar PDF published by ${props.districtName}. Check the district calendar page for revisions before making travel or child care plans.`
})
const pdfVersionLabel = computed(() =>
  props.cal?.pdfVersionLabel ?? props.cal?.meta?.pdfVersionLabel ?? props.cal?.sourceVersion ?? ''
)
const pdfButtonLabel = computed(() => {
  const customLabel = props.cal?.pdfButtonLabel ?? props.cal?.meta?.pdfButtonLabel
  if (customLabel) return customLabel
  if (isArchivedPdfCopy.value) return 'View Archived Copy of Official PDF'
  if (hasGeneratedPrintablePdf.value) return 'Download Printable PDF Calendar'
  if (isDrivePdf.value) return 'Download PDF'
  return 'View Official PDF'
})

const copied = ref(false)
const icsHref = computed(() => `/calendars/${props.district.slug}-${props.cal.schoolYear}.ics`)
const icsFilename = computed(() => `${props.district.slug}-${props.cal.schoolYear}.ics`)
const calendarShortName = computed(() => props.district?.shortName || props.districtName)
const icsHeading = computed(() =>
  props.cal?.icsHeading ?? props.cal?.meta?.icsHeading ?? `Download the ${displayYear.value} Calendar`
)
const icsDescription = computed(() =>
  props.cal?.icsDescription ?? props.cal?.meta?.icsDescription ?? `Download these dates as an ICS file for Google Calendar, Apple Calendar, or Outlook. This is a one-time import and will not update automatically if the district changes its calendar.`
)
const icsButtonLabel = computed(() => {
  return props.cal?.icsButtonLabel ?? props.cal?.meta?.icsButtonLabel ?? `Download ICS Calendar`
})
const icsButtonSupportText = computed(() =>
  props.cal?.icsButtonSupportText ?? props.cal?.meta?.icsButtonSupportText ?? 'One-time import. This calendar does not automatically sync with later district updates.'
)
const compatibleCalendars = ['Apple Calendar', 'Google Calendar', 'Outlook']
const icsIncludedItems = computed(() => {
  const events = props.cal?.events ?? []
  const hasType = (types: string[]) => events.some((event: any) => types.includes(event.type))
  const items = ['student holidays', 'break ranges']
  if (hasType(['no_school', 'student_holiday'])) items.push('student no-school dates')
  if (hasType(['early_dismissal', 'early_release'])) items.push('early-release dates')
  if (hasType(['school_resume', 'school_reopen'])) items.push('school resume dates')
  if (hasType(['academic', 'quarter_end', 'semester_end'])) items.push('key academic dates')
  return [...new Set(items)]
})
const icsIncludedText = computed(() => {
  const items = icsIncludedItems.value
  if (items.length <= 1) return items[0] ?? 'school calendar dates'
  return `${items.slice(0, -1).join(', ')}, and ${items[items.length - 1]}`
})
function copyLink() {
  navigator.clipboard.writeText(window.location.href)
  copied.value = true
  setTimeout(() => { copied.value = false }, 2000)
}
function shareWhatsApp() {
  const text = encodeURIComponent(`${props.districtName} ${props.year} school calendar — ${window.location.href}`)
  window.open(`https://wa.me/?text=${text}`, '_blank')
}
function shareSMS() {
  const text = encodeURIComponent(`${props.districtName} ${props.year} school calendar: ${window.location.href}`)
  window.open(`sms:?body=${text}`)
}
function printCalendar() {
  window.print()
}
const icsAriaLabel = computed(() => `Download ${props.districtName} ${props.year} calendar file for Google Calendar, Apple Calendar, and Outlook`)
</script>

