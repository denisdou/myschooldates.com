    <!-- Add to Calendar -->
    <div class="p-6 border-b border-[#ebe6dd]">
      <h2 class="text-lg font-semibold text-[#1f2933] mb-1">{{ icsHeading }}</h2>
      <p class="text-sm text-[#6b645c] mb-4">
        {{ icsDescription }}
      </p>
      <!-- Primary CTA -->
      <a
